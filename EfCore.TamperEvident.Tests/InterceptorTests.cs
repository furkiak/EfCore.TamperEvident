    public class RenamedItem
    {
        public int Id { get; set; }
        public required string Name { get; set; }
    }

    public class RenamedDbContext : DbContext
    {
        private readonly Microsoft.Data.Sqlite.SqliteConnection _connection;
        private readonly TamperEvidentOptions _options;

        public RenamedDbContext(Microsoft.Data.Sqlite.SqliteConnection connection, TamperEvidentOptions options)
        {
            _connection = connection;
            _options = options;
        }

        public DbSet<RenamedItem> Items => Set<RenamedItem>();

        protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder) =>
            optionsBuilder.UseSqlite(_connection).UseTamperEvidentAudit(_options);

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<RenamedItem>().ToTable("RenamedItems");
            modelBuilder.ApplyTamperEvidentAudit(auditLogTable: "tbl_audit", chainStateTable: "tbl_chain");

            // A naming convention such as snake_case renames every column.
            modelBuilder.Entity<AuditChainState>().Property(x => x.TableName).HasColumnName("table_name");
            modelBuilder.Entity<AuditChainState>().Property(x => x.LastHash).HasColumnName("last_hash");
            modelBuilder.Entity<AuditChainState>().Property(x => x.LastSequence).HasColumnName("last_sequence");
        }
    }

    public class NoAuditTablesContext : DbContext
    {
        public NoAuditTablesContext(DbContextOptions<NoAuditTablesContext> options) : base(options) { }

        public DbSet<RenamedItem> Items => Set<RenamedItem>();
    }
