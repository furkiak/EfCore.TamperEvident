        [Fact]
        public async Task SequenceNumbers_AreConsecutive_AndHashesAreLinked()
        {
            using var harness = new Harness();
            await using (var db = harness.CreateContext())
            {
                for (var i = 0; i < 5; i++)
                {
                    db.Customers.Add(new Customer { Name = $"c{i}" });
                    await db.SaveChangesAsync();
                }
            }

            await using var verify = harness.CreateContext();
            var logs = (await verify.AuditLogs.ToListAsync()).OrderBy(l => l.SequenceNumber).ToList();

            Assert.Equal(new long[] { 1, 2, 3, 4, 5 }, logs.Select(l => l.SequenceNumber));
            Assert.Equal("GENESIS", logs[0].PreviousHash);
            for (var i = 1; i < logs.Count; i++)
            {
                Assert.Equal(logs[i - 1].CurrentHash, logs[i].PreviousHash);
            }

            var state = await verify.AuditChainStates.SingleAsync();
            Assert.Equal(logs[^1].CurrentHash, state.LastHash);
            Assert.Equal(5, state.LastSequence);
            Assert.False(string.IsNullOrEmpty(state.Mac));
        }

        [Fact]
        public async Task Update_RecordsOnlyTheChangedProperties()
        {
            using var harness = new Harness();
            await using (var db = harness.CreateContext())
            {
                db.Customers.Add(new Customer { Name = "Before", Email = "keep@example.com", Balance = 10m });
                await db.SaveChangesAsync();
            }

            await using (var db = harness.CreateContext())
            {
                var customer = await db.Customers.SingleAsync();
                customer.Name = "After";
                customer.Balance = 25.5m;
                await db.SaveChangesAsync();
            }

            await using var verify = harness.CreateContext();
            var log = await verify.AuditLogs.SingleAsync(l => l.ActionType == AuditActions.Modified);

            // Only the two changed properties are recorded; "Email" did not change and is left out.
            using var oldValues = JsonDocument.Parse(log.OldValues!);
            using var newValues = JsonDocument.Parse(log.NewValues!);
            Assert.Equal(new[] { "Balance", "Name" }, oldValues.RootElement.EnumerateObject().Select(p => p.Name));
            Assert.Equal(new[] { "Balance", "Name" }, newValues.RootElement.EnumerateObject().Select(p => p.Name));
            Assert.Equal(10m, oldValues.RootElement.GetProperty("Balance").GetDecimal());
            Assert.Equal("Before", oldValues.RootElement.GetProperty("Name").GetString());
            Assert.Equal(25.5m, newValues.RootElement.GetProperty("Balance").GetDecimal());
            Assert.Equal("After", newValues.RootElement.GetProperty("Name").GetString());
        }

