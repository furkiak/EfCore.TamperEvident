        [Fact]
        public async Task TableAndColumnNames_AreTakenFromTheModel()
        {
            using var connection = new Microsoft.Data.Sqlite.SqliteConnection("DataSource=:memory:");
            connection.Open();
            var options = new TamperEvidentOptions { HmacSecretKey = Harness.SecretKey };

            await using (var db = new RenamedDbContext(connection, options))
            {
                await db.Database.EnsureCreatedAsync();
                db.Items.Add(new RenamedItem { Name = "custom names" });
                await db.SaveChangesAsync();
            }

            await using (var db = new RenamedDbContext(connection, options))
            {
                var log = await db.Set<AuditLog>().SingleAsync();
                Assert.Equal("RenamedItems", log.TableName);
                var state = await db.Set<AuditChainState>().SingleAsync();
                Assert.Equal(log.CurrentHash, state.LastHash);

                var tables = await db.Database.SqlQueryRaw<string>("SELECT name AS Value FROM sqlite_master WHERE type = 'table'").ToListAsync();
                Assert.Contains("tbl_audit", tables);
                Assert.Contains("tbl_chain", tables);
                Assert.DoesNotContain("AuditLogs", tables);
            }
        }

