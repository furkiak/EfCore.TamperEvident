using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Microsoft.EntityFrameworkCore;

namespace EfCore.TamperEvident.Models
{
    /// <summary>
    /// One sealed entry of the audit trail. Every entry stores the hash of its predecessor,
    /// which links all entries of a table into a tamper-evident chain.
    /// </summary>
    [Index(nameof(TableName), nameof(SequenceNumber), Name = "IX_AuditLogs_Table_Sequence")]
    [Index(nameof(TableName), nameof(RecordId), Name = "IX_AuditLogs_Table_Record")]
    [Index(nameof(TableName), nameof(PreviousHash), IsUnique = true, Name = "UX_AuditLogs_Table_PreviousHash")]
    public class AuditLog
    {
        /// <summary>Unique identifier of the entry. Generated by EF Core when left empty.</summary>
        [Key]
        public Guid Id { get; set; }

        /// <summary>Name of the audited table.</summary>
        [MaxLength(128)]
        public required string TableName { get; set; }

        /// <summary>Primary key of the audited row (composite keys are joined with <c>|</c>).</summary>
        [MaxLength(256)]
        public required string RecordId { get; set; }

        /// <summary>One of the <see cref="AuditActions"/> values.</summary>
        [MaxLength(32)]
        public required string ActionType { get; set; }

        /// <summary>Deterministic JSON with the previous values (updates and deletes).</summary>
        public string? OldValues { get; set; }

        /// <summary>Deterministic JSON with the new values (inserts and updates).</summary>
        public string? NewValues { get; set; }

        /// <summary>The user the change is attributed to.</summary>
        [MaxLength(256)]
        public required string UserId { get; set; }

        /// <summary>UTC timestamp of the entry, in <see cref="DateTime.Ticks"/>.</summary>
        public long TimestampTicks { get; set; }

        /// <summary>
        /// Position of the entry inside the chain of its table (starting at 1).
        /// Entries written by 1.x releases carry <c>0</c>.
        /// </summary>
        public long SequenceNumber { get; set; }

        /// <summary>See <see cref="AuditHashVersion"/>.</summary>
        public int HashVersion { get; set; } = AuditHashVersion.Canonical;

        /// <summary>Identifier of the HMAC key that sealed the entry (<c>null</c> when no key id is configured).</summary>
        [MaxLength(64)]
        public string? KeyId { get; set; }

        /// <summary>Hash of the previous entry (<c>GENESIS</c> for the first entry of a table).</summary>
        [MaxLength(64)]
        public required string PreviousHash { get; set; }

        /// <summary>HMAC-SHA256 of this entry, hex encoded.</summary>
        [MaxLength(64)]
        public required string CurrentHash { get; set; }

        /// <summary>The timestamp of the entry as a UTC <see cref="DateTime"/>.</summary>
        [NotMapped]
        public DateTime TimestampUtc => new DateTime(TimestampTicks, DateTimeKind.Utc);
    }
}
